#!/usr/bin/env python3
"""Procedural retro sound effects, sfxr-style, standard library only (no GPU, no downloads).

    python sfx_synth.py coin --count 4 --out sfx/raw            # sfx/raw/coin_01.wav ... coin_04.wav
    python sfx_synth.py laser --seed 7 --out sfx/raw
    python sfx_synth.py explosion hit jump blip powerup --count 3 --out sfx/raw
    python sfx_synth.py --list

Each preset is a recipe with random ranges, so --count gives variations of the same idea, and --seed makes
them repeatable. Output: 44.1 kHz mono 16-bit WAV, peak at -1 dBFS. Everything this writes is yours (it is
generated by code in this repo; no samples or models are involved).

Good for: UI blips and confirms, pickups, retro lasers, jumps, small hits, power-ups, and as the sharp
transient layered on top of a recorded or AI-generated body (see the game-sfx SKILL.md).
"""
import argparse
import math
import os
import random
import struct
import wave

RATE = 44100

# Each value is (low, high) for a uniform draw, or a fixed value.
PRESETS = {
    "coin":      dict(wave="square", f0=(900, 1400), slide=0.0, jump=(1.25, 1.6), jump_at=(0.05, 0.09), attack=0.0, sustain=(0.05, 0.09), decay=(0.12, 0.25), duty=(0.4, 0.5)),
    "laser":     dict(wave=("square", "saw"), f0=(900, 1800), slide=(-3.5, -1.5), attack=0.0, sustain=(0.03, 0.08), decay=(0.08, 0.2), duty=(0.2, 0.5), vibrato=(0, 0.05), vib_hz=(15, 40)),
    "explosion": dict(wave="noise", f0=(60, 160), slide=(-0.6, -0.1), attack=0.0, sustain=(0.08, 0.2), decay=(0.4, 0.9), lowpass=(0.15, 0.45), punch=(0.3, 0.6)),
    "hit":       dict(wave=("noise", "square"), f0=(180, 500), slide=(-2.5, -0.8), attack=0.0, sustain=(0.01, 0.04), decay=(0.06, 0.16), lowpass=(0.4, 0.9), punch=(0.2, 0.5)),
    "jump":      dict(wave="square", f0=(250, 450), slide=(0.8, 2.2), attack=0.0, sustain=(0.05, 0.12), decay=(0.08, 0.18), duty=(0.3, 0.5)),
    "blip":      dict(wave=("square", "sine"), f0=(600, 1300), slide=0.0, attack=0.0, sustain=(0.02, 0.05), decay=(0.02, 0.06), duty=0.5),
    "powerup":   dict(wave=("square", "saw"), f0=(300, 600), slide=(0.6, 1.4), attack=0.0, sustain=(0.15, 0.3), decay=(0.15, 0.3), vibrato=(0.02, 0.08), vib_hz=(8, 16), arp=(1.2, 1.5), arp_rate=(10, 18)),
}


def draw(rng, v):
    if isinstance(v, tuple) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        return rng.uniform(*v)
    if isinstance(v, tuple):
        return rng.choice(v)
    return v


def render(recipe, rng):
    p = {k: draw(rng, v) for k, v in recipe.items()}
    attack, sustain, decay = p.get("attack", 0.0), p["sustain"], p["decay"]
    total = attack + sustain + decay
    n = int(total * RATE)
    f0, slide = p["f0"], p.get("slide", 0.0)
    duty = p.get("duty", 0.5)
    vib, vib_hz = p.get("vibrato", 0.0), p.get("vib_hz", 0.0)
    jump, jump_at = p.get("jump", 1.0), p.get("jump_at", 1e9)
    arp, arp_rate = p.get("arp", 1.0), p.get("arp_rate", 0.0)
    lp = p.get("lowpass", 1.0)
    punch = p.get("punch", 0.0)
    phase, noise_val, lp_state = 0.0, 0.0, 0.0
    out = []
    for i in range(n):
        t = i / RATE
        freq = f0 * math.pow(2.0, slide * t)
        if t >= jump_at:
            freq *= jump
        if arp_rate and int(t * arp_rate) % 2:
            freq *= arp
        if vib:
            freq *= 1.0 + vib * math.sin(2 * math.pi * vib_hz * t)
        freq = max(20.0, min(freq, 18000.0))
        prev = phase
        phase = (phase + freq / RATE) % 1.0
        w = p["wave"]
        if w == "square":
            s = 1.0 if phase < duty else -1.0
        elif w == "saw":
            s = 2.0 * phase - 1.0
        elif w == "sine":
            s = math.sin(2 * math.pi * phase)
        else:  # noise: new random value each cycle of the base frequency
            if phase < prev:
                noise_val = rng.uniform(-1.0, 1.0)
            s = noise_val if freq < 2000 else rng.uniform(-1.0, 1.0)
        lp_state += lp * (s - lp_state)
        s = lp_state
        if t < attack:
            env = t / attack if attack else 1.0
        elif t < attack + sustain:
            env = 1.0 + punch * (1.0 - (t - attack) / sustain)
        else:
            env = max(0.0, 1.0 - (t - attack - sustain) / decay)
        out.append(s * env)
    # 2 ms fades so nothing clicks, then peak-normalise to -1 dBFS
    fade = int(0.002 * RATE)
    for i in range(min(fade, len(out))):
        out[i] *= i / fade
        out[-1 - i] *= i / fade
    peak = max((abs(x) for x in out), default=0.0) or 1.0
    gain = math.pow(10, -1 / 20) / peak
    return [x * gain for x in out], p


def write_wav(path, samples):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(b"".join(struct.pack("<h", int(max(-1.0, min(1.0, s)) * 32767)) for s in samples))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("presets", nargs="*", help="one or more of: " + ", ".join(PRESETS))
    ap.add_argument("--count", type=int, default=1)
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--out", default="sfx_raw")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    if a.list or not a.presets:
        print("presets:", ", ".join(PRESETS))
        return
    os.makedirs(a.out, exist_ok=True)
    rng = random.Random(a.seed)
    for name in a.presets:
        if name not in PRESETS:
            raise SystemExit("unknown preset %r (have: %s)" % (name, ", ".join(PRESETS)))
        for k in range(1, a.count + 1):
            samples, params = render(PRESETS[name], rng)
            path = os.path.join(a.out, "%s_%02d.wav" % (name, k))
            write_wav(path, samples)
            print("%s  %.2f s  %s" % (path, len(samples) / RATE, params["wave"]))


if __name__ == "__main__":
    main()
